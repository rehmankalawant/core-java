package com.rehman.operators;

public class RelationalOperators {
    public static void main(String[] args) {

//        Relational Operator
//        Relational operators are used to compare / to show relation between two or more variables .

//        Types of Relational Operator
//        1. GREATER THAN --> [ > ]
//        2. LESS THAN --> [ < ]
//        3. EQUALS TO --> [ = ]
//        4. GREATER EQUALS --> [ >= ]
//        5. LESS EQUALS --> [ <= ]
//        6. DOUBLE EQUALS --> [ == ]
//        6. NOT EQUALS --> [ != ]

        int a = 10, b = 20;

        System.out.println("Result for Greater Than " + (a > b));
        System.out.println("Result for Less Than " + (a < b));
        System.out.println("Result for Equals To " + (a = b));
        System.out.println("Result for Greater Equals " + (a >= b));
        System.out.println("Result for Less Equals " + (a <= b));
        System.out.println("Result for double Equals " + (a == b));
        System.out.println("Result for Not Equals " + (a != b));
    }
}